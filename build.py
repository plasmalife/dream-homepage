def make_features(feats):
    return "".join(f"<li>{f}</li>" for f in feats)

def make_detail_body(p):
    sections = p["detail_sections"]
    if not sections:
        return "<p style='color:#888;font-size:14px;'>상세 설명이 준비 중입니다.</p>"
    out = ""
    for title, content in sections:
        lines = content.split("\n")
        paras = "".join(f"<p>{l}</p>" for l in lines if l.strip())
        out += f"<div class='ds'><h4>{title}</h4>{paras}</div>"
    return out

